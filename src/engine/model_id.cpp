void
CModelIndexLimit::ReplaceStreamingBufferRefs(int maxModelId)
{
	// 0.98e @ RVA 0x17410 (FUN_10017410). Sites: plugin .data @ RVA 0xacde8.
	// BUGFIX(stable-1.0): (a) allocation is clamped to at least the copy size
	// below - the original (max*5+0x23)*4 form is 80 dwords SHORTER than the
	// (colBoundary*5+0x73)*4 copy whenever maxModelId < MvlColIdBoundary+16,
	// which heap-overflowed the fresh buffer for small configured model limits
	// (deviation: crash-guard clamp, buffer only grows); (b) the previous
	// MvlStreamingBuffer is now freed on the grow path - it was leaked (pointer
	// overwritten without free; the sibling ReplaceModelPointerBufferRefs frees
	// first); (c) capacity is committed only after a successful allocation
	// (was committed before malloc, leaving capacity>0 with buffer NULL).
	const size_t copyDwords = (static_cast<size_t>(MvlColIdBoundary) * 5 + 0x73);
	size_t allocBytes = (static_cast<size_t>(maxModelId) * 5 + 0x23) * 4;
	if (copyDwords * 4 > allocBytes)
		allocBytes = copyDwords * 4; // BUGFIX clamp (see above)

	void *oldBuffer = MvlStreamingBuffer;
	if (oldBuffer == NULL || MvlStreamingBufferCapacity < maxModelId) {
		void *fresh = malloc(allocBytes);
		if (fresh == NULL) {
			ReportProblem("CModelIndexLimit::ReplaceStreamingBufferRefs",
			              "Out of memory (%d models).", maxModelId);
			return; // old buffer + capacity untouched (consistent state)
		}
		MvlStreamingBufferCapacity = maxModelId;
		MvlStreamingBuffer = fresh;
		if (oldBuffer != NULL)
			free(oldBuffer); // BUGFIX(stable-1.0): was leaked (see header note)
	}

	uint8_t       *newBase = static_cast<uint8_t*>(MvlStreamingBuffer);
	const uint8_t *oldBase = MvlStreamingBufferBase;

	memcpy(MvlStreamingBuffer, MvlStreamingBufferBase,
	       (static_cast<size_t>(MvlColIdBoundary) * 5 + 0x73) * 4);

	for (size_t i = 0; i < sizeof(kStreamingBufferSites) / sizeof(kStreamingBufferSites[0]); ++i) {
		const uint32_t siteAddress = kStreamingBufferSites[i];

		// Original: skip only when long-model-ids are on AND the site is one of
		// the two sites handled specially elsewhere.
		if (MvlLongModelIdsEnabled != 0 &&
		    (siteAddress == kVC_StreamingSkipSite1 || siteAddress == kVC_StreamingSkipSite2))
			continue;

		uint32_t *site = reinterpret_cast<uint32_t*>(static_cast<uintptr_t>(siteAddress));
		const uint32_t stored = *site;
		const uint32_t oldBaseValue = static_cast<uint32_t>(reinterpret_cast<uintptr_t>(oldBase));

		if (stored < oldBaseValue || stored >= oldBaseValue + kStreamingBufferSize) {
			// Outside the old buffer. The only legal sites that are out of range
			// are the four rewritten directly by ReplaceTex/ColStartIndexRefs.
			if (siteAddress != kVC_TexStartRef1 && siteAddress != kVC_TexStartRef2 &&
			    siteAddress != kVC_ColStartRef2 && siteAddress != kVC_ColStartRef1) {
				ReportProblem("CModelIndexLimit::ReplaceStreamingBufferRefs",
				              "Problem at %08X.", siteAddress);
				// Original reloads puVar4/puVar6 here; MvlStreamingBuffer and
				// MvlStreamingBufferBase cannot have changed inside the loop -> no-op.
			}
		} else {
			*site = (stored - oldBaseValue) +
			        static_cast<uint32_t>(reinterpret_cast<uintptr_t>(newBase));
		}
	}

	MvlStreamingBufferBase = newBase;
	MvlWriteDword(reinterpret_cast<void*>(static_cast<uintptr_t>(kVC_StreamingCapacity)),
	              static_cast<uint32_t>(maxModelId));
}

void
CModelIndexLimit::ReplaceModelPointerBufferRefs(int maxModelId)
{
	// 0.98e @ RVA 0x17510 (FUN_10017510). Sites: plugin .data @ RVA 0xada18.
	if (MvlModelPointerBuffer != NULL && maxModelId > MvlModelPointerBufferCapacity) {
		free(MvlModelPointerBuffer);
		MvlModelPointerBuffer = NULL; // clone safety: keep state consistent if malloc fails
	}
	if (MvlModelPointerBuffer == NULL) {
		MvlModelPointerBufferCapacity = maxModelId;
		MvlModelPointerBuffer = malloc(static_cast<size_t>(maxModelId) * 4 + 0x1C);
		if (MvlModelPointerBuffer == NULL) {
			ReportProblem("CModelIndexLimit::ReplaceModelPointerBufferRefs",
			              "Out of memory (%d models).", maxModelId);
			return;
		}
	}

	const uint32_t newBaseValue = static_cast<uint32_t>(reinterpret_cast<uintptr_t>(MvlModelPointerBuffer));
	const uint32_t oldBaseValue = static_cast<uint32_t>(reinterpret_cast<uintptr_t>(MvlModelLookupRegistry));

	for (size_t i = 0; i < sizeof(kModelPointerSites) / sizeof(kModelPointerSites[0]); ++i) {
		const uint32_t siteAddress = kModelPointerSites[i];
		if (siteAddress == kVC_ModelPtrSkipSite)
			continue; // original skips 0x578A77

		uint32_t *site = reinterpret_cast<uint32_t*>(static_cast<uintptr_t>(siteAddress));
		const uint32_t stored = *site;

		if (stored < oldBaseValue || stored >= oldBaseValue + kModelPointerBufferRange) {
			bool handled = false;
			if (siteAddress == kVC_ModelPtrSpecialSite) {
				// Unaligned special case: the stored pointer sits at 0x45E865.
				uint32_t special;
				memcpy(&special,
				       reinterpret_cast<const void*>(static_cast<uintptr_t>(kVC_ModelPtrSpecialValue)),
				       sizeof(special));
				if (oldBaseValue <= special && special < oldBaseValue + kModelPointerBufferRange) {
					special = (special - oldBaseValue) + newBaseValue;
					memcpy(reinterpret_cast<void*>(static_cast<uintptr_t>(kVC_ModelPtrSpecialValue)),
					       &special, sizeof(special));
					handled = true;
				}
			}
			if (!handled) {
				ReportProblem("CModelIndexLimit::ReplaceModelPointerBufferRefs",
				              "Problem at %08X.", siteAddress);
			}
		} else {
			*site = (stored - oldBaseValue) + newBaseValue;
		}
	}

	MvlModelLookupRegistry = static_cast<uint32_t*>(MvlModelPointerBuffer);
}

void
CModelIndexLimit::ReplaceTexStartIndexRefs(int texStart, uint32_t texCount)
{
	// 0.98e @ RVA 0x175f0 (FUN_100175f0). Sites: plugin .data @ RVA 0xae390.
	for (size_t i = 0; i < sizeof(kTexStartSites) / sizeof(kTexStartSites[0]); ++i) {
		int *site = reinterpret_cast<int*>(static_cast<uintptr_t>(kTexStartSites[i]));
		if (*site == MvlModelIdBoundary)
			*site = texStart;
		else if (*site == -MvlModelIdBoundary)
			*site = -texStart;
		else
			ReportProblem("CModelIndexLimit::ReplaceTexStartIndexRefs", "Problem at %08X.",
			              kTexStartSites[i]);
	}

	const uint32_t newStart = static_cast<uint32_t>(reinterpret_cast<uintptr_t>(MvlStreamingBufferBase)) +
	                          8u + static_cast<uint32_t>(texStart) * 0x14u;
	MvlWriteDword(reinterpret_cast<void*>(static_cast<uintptr_t>(kVC_TexStartRef1)), newStart);
	MvlWriteDword(reinterpret_cast<void*>(static_cast<uintptr_t>(kVC_TexStartRef2)), newStart);
	MvlWriteDword(reinterpret_cast<void*>(static_cast<uintptr_t>(kVC_TexCountRef1)), texCount);
	MvlWriteDword(reinterpret_cast<void*>(static_cast<uintptr_t>(kVC_TexStartRef3)),
	              static_cast<uint32_t>(texStart));
	MvlWriteDword(reinterpret_cast<void*>(static_cast<uintptr_t>(kVC_TexCountRef2)), texCount);
	MvlWriteDword(reinterpret_cast<void*>(static_cast<uintptr_t>(kVC_TexCountRef3)), texCount);

	uint32_t *&vcTexPool = *reinterpret_cast<uint32_t**>(static_cast<uintptr_t>(kVC_TexPoolGlobal));
	if (vcTexPool != NULL) {
		uint32_t *oldPool = vcTexPool;
		vcTexPool = NULL;
		VcFunc<void (__cdecl *)(void)>(kVC_TexPoolRebuild1)();
		uint32_t *newPool = vcTexPool; // set by the VC rebuild call

		// BUGFIX(stable-1.0): the original trusted the VC rebuild (0x581010) to
		// repopulate the pool pointer; when it does not, the newPool[0/1]
		// derefs below crash on NULL. Restore the old pool pointer and bail
		// (deviation: crash-guard only; the site rewrites above already ran, so
		// the boundary is still advanced to keep state consistent).
		if (newPool == NULL) {
			vcTexPool = oldPool;
			MvlErrorLog("CModelIndexLimit::ReplaceTexStartIndexRefs: VC "
			            "tex-pool rebuild (RVA 0x181010) returned NULL - copy skipped");
			MvlModelIdBoundary = texStart;
			return;
		}

		int copyCount = MvlTxdIdBoundary - MvlModelIdBoundary;
		if (copyCount < 0)
			copyCount = 0; // BUGFIX(stable-1.0): negative count would wrap the
			               // size_t memcpy lengths to ~4GB (crash-guard)
		if (static_cast<int>(texCount) < copyCount)
			copyCount = static_cast<int>(texCount);
		const size_t copyBytes = static_cast<size_t>(static_cast<uint32_t>(copyCount));

		memcpy(reinterpret_cast<void*>(static_cast<uintptr_t>(newPool[1])),
		       reinterpret_cast<const void*>(static_cast<uintptr_t>(oldPool[1])), copyBytes);
		memcpy(reinterpret_cast<void*>(static_cast<uintptr_t>(newPool[0])),
		       reinterpret_cast<const void*>(static_cast<uintptr_t>(oldPool[0])),
		       copyBytes * kTexEntrySize);

		int mergedTexCount = static_cast<int>(newPool[2]);
		if (static_cast<int>(oldPool[3]) < static_cast<int>(newPool[2]))
			mergedTexCount = static_cast<int>(oldPool[3]);
		newPool[3] = static_cast<uint32_t>(mergedTexCount);

		vcTexPool = oldPool;
		VcFunc<void (__cdecl *)(void)>(kVC_TexPoolRebuild2)();
		MvlSavedTexturePool = newPool;
		vcTexPool = newPool;
	}

	MvlModelIdBoundary = texStart;
}

