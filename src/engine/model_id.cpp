static void
ReportProblem(const char *context, const char *format, ...)
{
	char msg[512];
	va_list args;

	va_start(args, format);
	vsnprintf(msg, sizeof(msg), format, args);
	va_end(args);

	MvlErrorLog("%s: %s", context, msg);
}

